#!/bin/bash
# Lerping@Home release publisher — the "ship it" half of the auto-updater.
#
# Usage: scripts/publish-release.sh [tag]   (default: vYYYY.MM.DD.HHMM)
#
# Builds the public release with `make release`: both bundles signed with
# Developer ID and hardened runtime, the PKG signed with Developer ID Installer,
# and the PKG and DMG notarized and stapled. Nothing is installed locally.
# It uploads four assets to a GitHub Release:
#
#   LerpingAtHome-saver-<tag>.zip   the notarized, stapled saver the playground's
#                                   updater (scripts/release-update.sh) installs;
#                                   its LerpBuild stamp must equal the tag
#   LerpingAtHome-<version>-arm64.dmg (+ .sha256)  the installer for people
#   LerpingAtHome-<tag>-source.tar.gz             AGPL Corresponding Source
#
# <version> is the tag without the leading v (the PKG needs a numeric version).
#
# Signing comes from the keychain. Override any of these if it guesses wrong:
#   APP_SIGN_IDENTITY        "Developer ID Application: …"
#   INSTALLER_SIGN_IDENTITY  "Developer ID Installer: …"
#   NOTARY_PROFILE           notarytool keychain profile (default: lerping)
# Create the profile once from an App Store Connect API key:
#   xcrun notarytool store-credentials lerping --key AuthKey_X.p8 --key-id X --issuer Y
#
# There is no unsigned mode. An unsigned public DMG is what this used to ship,
# with a note telling people to right-click → Open; Gatekeeper on current macOS
# no longer offers that way out.
#
# Requires a clean checkout (releases what you see), the Xcode command-line
# tools, and the `gh` CLI authenticated to codyhxyz/lerping-at-home.
set -euo pipefail

[ "$(uname -s)" = Darwin ] || { echo "publish-release.sh is macOS only." >&2; exit 1; }
command -v gh >/dev/null 2>&1 || { echo "the gh CLI is required (https://cli.github.com)." >&2; exit 1; }

TAG="${1:-v$(date '+%Y.%m.%d.%H%M')}"
# Match the installer's numeric version syntax and require a real git ref.
[[ "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.-]+)?$ ]] &&
    git check-ref-format "refs/tags/$TAG" || {
    echo "tag should look like v2026.09.16.1830 or v1.2.3 (got: $TAG)" >&2; exit 1;
}
if [[ "$TAG" == *-dirty || "$TAG" =~ -[0-9]+-g[0-9a-f]+$ ]]; then
    echo "tag looks like a local build: $TAG" >&2; exit 1
fi
VERSION="${TAG#v}" # the PKG requires a numeric-looking version, no v prefix

HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"
clean_checkout() {
    local status
    status="$(git status --porcelain --ignore-submodules=none)" && [ -z "$status" ]
}
clean_checkout || { echo "checkout is dirty or unreadable; commit or stash first." >&2; exit 1; }
COMMIT="$(git rev-parse HEAD)"
python3 -I scripts/verify-release-licenses.py --dry-run

# Archive committed inputs, never the working directory or a build cache.
# SwiftPM's source checkouts are generated by the same release build; verify
# the revisions against the committed lock before exporting them.
archive_source() {
    local source_name="LerpingAtHome-$TAG-source" dep revision checkout mediapipe_rev
    local SOURCE_ROOT="$WORK/$source_name"
    export SOURCE_ROOT
    mkdir "$SOURCE_ROOT"
    git archive "$COMMIT" | tar -xf - -C "$SOURCE_ROOT"
    git submodule foreach --quiet --recursive '
        set -e
        test "$(git rev-parse HEAD)" = "$sha1"
        mkdir -p "$SOURCE_ROOT/$displaypath"
        archive=$(mktemp)
        trap '\''rm -f "$archive"'\'' EXIT
        git archive "$sha1" > "$archive"
        tar -xf "$archive" -C "$SOURCE_ROOT/$displaypath"
    '
    python3 -c '
import json, re, sys
for pin in json.load(open(sys.argv[1]))["pins"]:
    name, revision = pin["identity"], pin["state"]["revision"]
    if not re.fullmatch(r"[a-zA-Z0-9_-]+", name) or not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("invalid SwiftPM dependency pin")
    print(name, revision)
' "$SOURCE_ROOT/Sources/MIDIDeps/Package.resolved" > "$WORK/swiftpm-pins"
    while read -r dep revision; do
        checkout="Sources/MIDIDeps/.build/checkouts/$dep"
        [ "$(git -C "$checkout" rev-parse HEAD)" = "$revision" ] &&
            [ -z "$(git -C "$checkout" status --porcelain --ignore-submodules=none)" ] || {
            echo "cannot archive mismatched SwiftPM checkout: $dep ($revision)" >&2; return 1;
        }
        mkdir -p "$SOURCE_ROOT/third_party/swiftpm/$dep"
        git -C "$checkout" archive "$revision" | tar -xf - -C "$SOURCE_ROOT/third_party/swiftpm/$dep"
    done < "$WORK/swiftpm-pins"

    # Source release tag v0.10.35 for the shipped npm JS/WASM. Fail closed
    # when the Makefile's npm pin changes until the source pin is updated.
    [ "$(awk '$1 == "MEDIAPIPE_VERSION" { print $3 }' "$SOURCE_ROOT/Makefile")" = 0.10.35 ] || {
        echo "update the MediaPipe source pin to match the release build" >&2; return 1;
    }
    mediapipe_rev=f8ef212d5c962c0e853db7e59d217056b187084b
    curl -fsSL --retry 3 -o "$WORK/mediapipe-source.tar.gz" \
        "https://codeload.github.com/google-ai-edge/mediapipe/tar.gz/$mediapipe_rev"
    mkdir "$SOURCE_ROOT/third_party/mediapipe"
    tar -xzf "$WORK/mediapipe-source.tar.gz" --strip-components 1 -C "$SOURCE_ROOT/third_party/mediapipe"

    cat > "$SOURCE_ROOT/RELEASE-SOURCE.txt" <<EOF
Lerping@Home $TAG
Project commit: $COMMIT
MediaPipe v0.10.35: $mediapipe_rev (third_party/mediapipe)
SwiftPM source pins: Sources/MIDIDeps/Package.resolved (third_party/swiftpm)

See README.md and Makefile for the macOS build instructions. Use
make package LERP_BUILD=$TAG RELEASE_VERSION=$VERSION RELEASE_BUILD=$RELEASE_BUILD
for the unsigned installer. The release staging step applies the commercial
asset policy. Separately licensed media and models are documented in NOTICE.txt.
EOF
    tar -czf "$WORK/$source_name.tar.gz" -C "$WORK" "$source_name"
}

# First quoted name of a valid identity matching $2, from `security find-identity`.
identity() {
    security find-identity -v $1 | sed -n "s/.*\"\\($2: [^\"]*\\)\".*/\\1/p" | head -n 1
}
APP_SIGN_IDENTITY="${APP_SIGN_IDENTITY:-$(identity '-p codesigning' 'Developer ID Application')}"
INSTALLER_SIGN_IDENTITY="${INSTALLER_SIGN_IDENTITY:-$(identity '-p basic' 'Developer ID Installer')}"
NOTARY_PROFILE="${NOTARY_PROFILE:-lerping}"

missing=0
[ -n "$APP_SIGN_IDENTITY" ] || { echo "no Developer ID Application identity in the keychain." >&2; missing=1; }
[ -n "$INSTALLER_SIGN_IDENTITY" ] || { echo "no Developer ID Installer identity in the keychain." >&2; missing=1; }
xcrun notarytool history --keychain-profile "$NOTARY_PROFILE" >/dev/null 2>&1 \
    || { echo "notarytool profile '$NOTARY_PROFILE' is missing or invalid." >&2; missing=1; }
if [ "$missing" = 1 ]; then
    echo "Developer ID certificates can only be made by the Account Holder: Xcode → Settings →" >&2
    echo "Accounts → Manage Certificates → + → Developer ID Application / Developer ID Installer." >&2
    exit 1
fi
echo "==> signing as $APP_SIGN_IDENTITY"
echo "    packaging as $INSTALLER_SIGN_IDENTITY"
echo "    notarizing with profile $NOTARY_PROFILE"

if gh release view "$TAG" >/dev/null 2>&1; then
    echo "release $TAG already exists; pass a different tag." >&2
    exit 1
fi

# gh uses --target only when creating the tag. Reject a pre-existing remote
# tag that points anywhere else, including an annotated tag's peeled commit.
REMOTE_TAG="$(git ls-remote origin "refs/tags/$TAG" "refs/tags/$TAG^{}" | tail -n 1 | cut -f 1)"
[ -z "$REMOTE_TAG" ] || [ "$REMOTE_TAG" = "$COMMIT" ] || {
    echo "remote tag $TAG does not match release commit $COMMIT" >&2; exit 1;
}
git submodule update --init --recursive --checkout
clean_checkout || { echo "submodule checkout is dirty or unreadable" >&2; exit 1; }
RELEASE_BUILD="$(git rev-list --count "$COMMIT")"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "==> building, signing, and notarizing the release"
make release LERP_BUILD="$TAG" RELEASE_VERSION="$VERSION" RELEASE_BUILD="$RELEASE_BUILD" \
    APP_SIGN_IDENTITY="$APP_SIGN_IDENTITY" \
    INSTALLER_SIGN_IDENTITY="$INSTALLER_SIGN_IDENTITY" \
    NOTARY_PROFILE="$NOTARY_PROFILE"
DMG="build/release/LerpingAtHome-$VERSION-arm64.dmg"
[ -f "$DMG" ] && [ -f "$DMG.sha256" ] || { echo "make release did not produce $DMG and its checksum" >&2; exit 1; }

# The updater zip is the saver staged inside the PKG: Developer ID signed, with
# the same stamp. Notarize it on its own and staple the ticket to the bundle,
# so it passes Gatekeeper offline wherever the updater puts it.
STAGED="build/release/saver-root/Library/Screen Savers/Lerping@Home.saver"
[ "$(plutil -extract LerpBuild raw "$STAGED/Contents/Info.plist")" = "$TAG" ] \
    || { echo "release saver stamp is not $TAG" >&2; exit 1; }

ASSET="LerpingAtHome-saver-$TAG.zip"
ditto "$STAGED" "$WORK/Lerping@Home.saver"
ditto -c -k --keepParent "$WORK/Lerping@Home.saver" "$WORK/notarize.zip"
echo "==> notarizing the updater saver"
xcrun notarytool submit "$WORK/notarize.zip" --keychain-profile "$NOTARY_PROFILE" --wait
xcrun stapler staple "$WORK/Lerping@Home.saver"
xcrun stapler validate "$WORK/Lerping@Home.saver"
(cd "$WORK" && ditto -c -k --keepParent "Lerping@Home.saver" "$ASSET")

# The zip must round-trip to the same signed, stapled, correctly stamped bundle.
mkdir "$WORK/check"
ditto -x -k "$WORK/$ASSET" "$WORK/check"
codesign --verify --deep --strict "$WORK/check/Lerping@Home.saver"
xcrun stapler validate "$WORK/check/Lerping@Home.saver"
[ "$(plutil -extract LerpBuild raw "$WORK/check/Lerping@Home.saver/Contents/Info.plist")" = "$TAG" ]

python3 -I scripts/verify-release-licenses.py "$DMG" "$WORK/$ASSET"
[ "$(git rev-parse HEAD)" = "$COMMIT" ] && clean_checkout || {
    echo "checkout changed during release build" >&2; exit 1;
}
echo "==> archiving Corresponding Source for $TAG ($COMMIT)"
archive_source

echo "==> publishing release $TAG"
gh release create "$TAG" --target "$COMMIT" \
    --title "Lerping@Home $TAG" \
    --notes "Download LerpingAtHome-$VERSION-arm64.dmg, open it, and double-click **Install Lerping@Home**. Signed with Developer ID and notarized by Apple. The .sha256 file is its checksum. LerpingAtHome-saver-$TAG.zip feeds the playground's automatic updater. Download LerpingAtHome-$TAG-source.tar.gz for the AGPL Corresponding Source." \
    "$WORK/$ASSET" \
    "$DMG" \
    "$DMG.sha256" \
    "$WORK/LerpingAtHome-$TAG-source.tar.gz"

cat <<EOF

Published $TAG with the updater ZIP, notarized installer DMG, and Corresponding
Source archive. Automatic updates require a trusted, writable installation;
use the signed DMG for initial installation or to refresh a system installation
that requires administrator access. Update the playground separately via the DMG.
EOF
